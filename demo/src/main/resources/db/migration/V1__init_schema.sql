CREATE TABLE teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    short_name VARCHAR(20) NOT NULL,
    league VARCHAR(80) NOT NULL,
    logo_url VARCHAR(500)
);

CREATE TABLE matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_team_id BIGINT NOT NULL,
    away_team_id BIGINT NOT NULL,
    kickoff_at TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    venue VARCHAR(160),
    CONSTRAINT fk_match_home_team FOREIGN KEY (home_team_id) REFERENCES teams(id),
    CONSTRAINT fk_match_away_team FOREIGN KEY (away_team_id) REFERENCES teams(id)
);

CREATE TABLE odds_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    home_win DECIMAL(8, 3) NOT NULL,
    draw DECIMAL(8, 3) NOT NULL,
    away_win DECIMAL(8, 3) NOT NULL,
    recorded_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_odds_match FOREIGN KEY (match_id) REFERENCES matches(id)
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(180) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    role VARCHAR(30) NOT NULL
);

CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(180) NOT NULL,
    message VARCHAR(500) NOT NULL,
    read_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX idx_odds_match_recorded ON odds_history(match_id, recorded_at);
